# 本地启动 LightRAG Server（可选）
#
# 前置：
#   1) 当前 PowerShell 会话里有 DEEPSEEK_API_KEY / DASHSCOPE_API_KEY，
#      或者把 scripts/lightrag.env.example 复制成 scripts/lightrag.env 并填好
#   2) 已安装 uv（uvx 在 PATH 上）
#
# 用法（二选一）：
#   $env:DEEPSEEK_API_KEY="sk-..."
#   $env:DASHSCOPE_API_KEY="sk-..."
#   .\scripts\start-lightrag.ps1
#
#   或：
#   Copy-Item .\scripts\lightrag.env.example .\scripts\lightrag.env
#   notepad .\scripts\lightrag.env
#   .\scripts\start-lightrag.ps1
#
# 启动后：
#   Swagger: http://localhost:9621/docs
#   WebUI:   http://localhost:9621/webui

param(
    [int]$Port = 9621,
    [string]$WorkingDir = "$PSScriptRoot\..\lightrag-data"
)

$ErrorActionPreference = "Stop"

# 可选：从 scripts/lightrag.env 读取 key；该文件已在 .gitignore，不会入库。
# 已经存在的环境变量优先，避免误覆盖。
$envFile = Join-Path $PSScriptRoot "lightrag.env"
if (Test-Path $envFile) {
    Get-Content $envFile -Encoding UTF8 | ForEach-Object {
        $line = $_.Trim()
        if ($line -and -not $line.StartsWith("#")) {
            $eq = $line.IndexOf("=")
            if ($eq -gt 0) {
                $name = $line.Substring(0, $eq).Trim()
                $value = $line.Substring($eq + 1).Trim()
                if (($value.StartsWith('"') -and $value.EndsWith('"')) -or
                    ($value.StartsWith("'") -and $value.EndsWith("'"))) {
                    $value = $value.Substring(1, $value.Length - 2)
                }
                if (@("DEEPSEEK_API_KEY", "DASHSCOPE_API_KEY", "LIGHTRAG_API_KEY") -contains $name) {
                    if (-not (Get-Item "Env:$name" -ErrorAction SilentlyContinue)) {
                        Set-Item -Path "Env:$name" -Value $value
                    }
                }
            }
        }
    }
}

if (-not $env:DEEPSEEK_API_KEY) {
    Write-Error "缺少 DEEPSEEK_API_KEY：请设置环境变量，或复制 scripts/lightrag.env.example 为 scripts/lightrag.env 并填写"
    exit 1
}
if (-not $env:DASHSCOPE_API_KEY) {
    Write-Error "缺少 DASHSCOPE_API_KEY：请设置环境变量，或复制 scripts/lightrag.env.example 为 scripts/lightrag.env 并填写"
    exit 1
}
if (-not (Get-Command uvx -ErrorAction SilentlyContinue)) {
    Write-Error "找不到 uvx，请先安装 uv：https://docs.astral.sh/uv/"
    exit 1
}

$resolvedWorkDir = [System.IO.Path]::GetFullPath($WorkingDir)
New-Item -ItemType Directory -Force -Path $resolvedWorkDir | Out-Null

# LightRAG 的 LLM / Embedding 都走 OpenAI 兼容协议：
# - LLM 用 DeepSeek
# - Embedding 用 DashScope 的 text-embedding-v4（与项目 document_chunk 的 1024 维一致）
$env:LLM_BINDING = "openai"
$env:LLM_MODEL = "deepseek-chat"
$env:LLM_BINDING_HOST = "https://api.deepseek.com/v1"
$env:LLM_BINDING_API_KEY = $env:DEEPSEEK_API_KEY

$env:EMBEDDING_BINDING = "openai"
$env:EMBEDDING_MODEL = "text-embedding-v4"
$env:EMBEDDING_DIM = "1024"
$env:EMBEDDING_BINDING_HOST = "https://dashscope.aliyuncs.com/compatible-mode/v1"
$env:EMBEDDING_BINDING_API_KEY = $env:DASHSCOPE_API_KEY

# Windows 控制台默认 GBK，LightRAG 启动横幅含 emoji，会抛 UnicodeEncodeError。
# 统一 Python/控制台为 UTF-8，避免服务还没启动就崩在打印上。
$env:PYTHONIOENCODING = "utf-8"
$env:PYTHONUTF8 = "1"
try {
    [Console]::OutputEncoding = New-Object System.Text.UTF8Encoding($false)
    $OutputEncoding = New-Object System.Text.UTF8Encoding($false)
} catch {
    # 非交互终端（重定向到日志）忽略即可
}

# 可选：如果你希望 LightRAG 也开 API Key，先设置 LIGHTRAG_API_KEY；
# 后端要用同一个值配 recordandgrow.graph.lightrag.api-key（或 LIGHTRAG_API_KEY）。

Write-Host "LightRAG 数据目录: $resolvedWorkDir"
Write-Host "LightRAG 地址:    http://localhost:$Port"
Write-Host "Swagger:          http://localhost:$Port/docs"
Write-Host "WebUI:            http://localhost:$Port/webui"
Write-Host "首次启动会加载依赖并初始化存储，耐心等 10-30 秒。"

# LightRAG 启动时会检查当前目录是否有 .env；没有会交互式问 yes/no。
# 这里用无 BOM 的空 .env 绕过检查，真正的配置仍由上面的环境变量提供。
$envPath = Join-Path $resolvedWorkDir ".env"
if (-not (Test-Path $envPath)) {
    [IO.File]::WriteAllText($envPath, "# generated by scripts/start-lightrag.ps1`n",
        (New-Object System.Text.UTF8Encoding($false)))
}
# 本地 guest 模式也要一个稳定 secret，避免每次重启 token 失效
if (-not $env:TOKEN_SECRET) {
    $env:TOKEN_SECRET = [guid]::NewGuid().ToString("N")
}

Push-Location $resolvedWorkDir
try {
    & uvx --from "lightrag-hku[api]" lightrag-server `
        --host 0.0.0.0 `
        --port $Port `
        --working-dir $resolvedWorkDir
} finally {
    Pop-Location
}
