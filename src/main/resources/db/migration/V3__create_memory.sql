-- V3: 对话、消息与长期记忆（模块十）
-- 设计原则：用户主动记录/确认的才是事实；AI 提炼的一律先落 PENDING，确认后才生效。
-- 会话记忆 = 最近若干条原文 + 一段滚动摘要；摘要与原文分开存，原文永不丢。

CREATE TABLE conversation (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                    VARCHAR(200) NOT NULL DEFAULT '新对话',
    summary                  TEXT,
    -- 摘要覆盖到哪条消息（不含）：历史加载时只取 id 大于它的消息
    summary_upto_message_id  BIGINT       NOT NULL DEFAULT 0,
    message_count            INT          NOT NULL DEFAULT 0,
    created_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted                  BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE message (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  BIGINT      NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    role             VARCHAR(20) NOT NULL,          -- USER / ASSISTANT / SYSTEM
    content          TEXT        NOT NULL,
    -- 来源快照（SSE sources 的 JSON），用于回看当时依据；可为空
    sources          TEXT,
    token_count      INT         NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_message_conversation ON message (conversation_id, id);

CREATE TABLE memory (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- PENDING：AI 提炼的候选，待确认；FACT：用户事实；INFERRED：用户确认过的推断
    type             VARCHAR(20) NOT NULL,
    -- PENDING 时记录"确认后应落入哪种类型"，确认时直接用
    proposed_type    VARCHAR(20),
    content          VARCHAR(500) NOT NULL,
    -- 去重/检索用：小写、压空白后的内容
    normalized       VARCHAR(500) NOT NULL,
    -- 证据 JSON：[{"type":"timeline","id":1,"excerpt":"..."}]
    evidence         TEXT,
    source           VARCHAR(40) NOT NULL,          -- USER / AI_EXTRACTED / AI_DOCUMENT
    confidence       REAL,
    conversation_id  BIGINT REFERENCES conversation (id) ON DELETE SET NULL,
    confirmed_at     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted          BOOLEAN     NOT NULL DEFAULT FALSE
);

-- 同一内容只允许一条待确认候选，避免每轮对话重复生成
CREATE UNIQUE INDEX uk_memory_pending_normalized
    ON memory (normalized) WHERE deleted = FALSE AND type = 'PENDING';
-- 记忆页按类型倒序展示；检索按类型 + 更新时间
CREATE INDEX idx_memory_type_updated ON memory (type, updated_at DESC) WHERE deleted = FALSE;
CREATE INDEX idx_memory_conversation ON memory (conversation_id) WHERE deleted = FALSE;
