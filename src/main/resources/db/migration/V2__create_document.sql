-- V2: 文档与文档分块
-- 原文不进库，DB 只存 sha256、宿主机路径与解析后的归一化全文。
-- document_chunk 是派生数据：重跑时物理删除重建，不做软删。
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE document (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(200) NOT NULL,
    file_name        VARCHAR(255) NOT NULL,
    mime_type        VARCHAR(100) NOT NULL,
    file_size        BIGINT       NOT NULL,
    storage_path     VARCHAR(500) NOT NULL,
    content_sha256   CHAR(64)     NOT NULL,
    normalized_text  TEXT,                                  -- 归一化全文，仅服务端使用，永不出接口
    status           VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    chunk_count      INT          NOT NULL DEFAULT 0,
    char_count       INT          NOT NULL DEFAULT 0,
    token_count      INT          NOT NULL DEFAULT 0,
    retry_count      INT          NOT NULL DEFAULT 0,       -- 对账补发次数，防止 MQ 重投叠加成死循环
    chunk_truncated  BOOLEAN      NOT NULL DEFAULT FALSE,
    error_message    VARCHAR(500),
    -- 处理进度心跳：状态切换与每批 embedding 写完都刷新。
    -- 对账用它判断「卡住」，不能用 updated_at（消费过程中不会变，会把大文档误判成卡住）。
    last_progress_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted          BOOLEAN      NOT NULL DEFAULT FALSE
);

-- 去重：只约束未删除的行，软删后允许重新上传同一份内容
CREATE UNIQUE INDEX uk_document_sha256_active ON document (content_sha256) WHERE deleted = FALSE;
-- 对账按它扫
CREATE INDEX idx_document_status_progress ON document (status, last_progress_at);

CREATE TABLE document_chunk (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     BIGINT      NOT NULL REFERENCES document (id) ON DELETE CASCADE,
    chunk_index     INT         NOT NULL,
    content         TEXT        NOT NULL,
    heading         VARCHAR(500),
    char_start      INT         NOT NULL,                   -- 以 code point 计
    char_end        INT         NOT NULL,
    char_count      INT         NOT NULL,
    token_count     INT         NOT NULL,
    embedding       vector(1024),
    embedding_model VARCHAR(64),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 同一文档的块序号唯一：重复解析插入同一序号会直接冲突，而不是悄悄产生两份
CREATE UNIQUE INDEX uk_document_chunk_index ON document_chunk (document_id, chunk_index);
-- 断点续跑：只补 embedding 为空的行
CREATE INDEX idx_document_chunk_pending ON document_chunk (document_id) WHERE embedding IS NULL;
CREATE INDEX idx_document_chunk_embedding ON document_chunk USING hnsw (embedding vector_cosine_ops);
