-- V4: 知识图谱（模块七）
-- 不引 Neo4j：单用户、图规模很小，Postgres 两张表 + 1 跳查询足够；
-- 需要 LightRAG/Neo4j 时通过 GraphStore 接口替换，领域层不感知。
-- 图是派生数据：文档重跑时按 document_id 物理删除重建。

CREATE TABLE graph_node (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(200) NOT NULL,
    normalized   VARCHAR(200) NOT NULL,
    type         VARCHAR(40)  NOT NULL DEFAULT 'CONCEPT',
    document_id  BIGINT       NOT NULL REFERENCES document (id) ON DELETE CASCADE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX uk_graph_node_document_normalized ON graph_node (document_id, normalized);
CREATE INDEX idx_graph_node_normalized ON graph_node (normalized);

CREATE TABLE graph_edge (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id    BIGINT       NOT NULL REFERENCES graph_node (id) ON DELETE CASCADE,
    target_id    BIGINT       NOT NULL REFERENCES graph_node (id) ON DELETE CASCADE,
    relation     VARCHAR(100) NOT NULL,
    document_id  BIGINT       NOT NULL REFERENCES document (id) ON DELETE CASCADE,
    weight       REAL         NOT NULL DEFAULT 1.0,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_graph_edge UNIQUE (source_id, target_id, relation, document_id)
);

CREATE INDEX idx_graph_edge_source ON graph_edge (source_id);
CREATE INDEX idx_graph_edge_target ON graph_edge (target_id);
CREATE INDEX idx_graph_edge_document ON graph_edge (document_id);
